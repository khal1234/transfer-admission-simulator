def josa(word, a, b):
    """받침 있으면 a, 없으면 b."""
    ch = word.rstrip(")>")[-1]
    code = ord(ch) - 0xAC00
    if 0 <= code < 11172:
        return a if code % 28 else b
    return b


def names(deps):
    if len(deps) <= 5:
        s = "·".join(deps)
        return s + josa(deps[-1], "은", "는")
    return f"{deps[0]}·{deps[1]} 등 {len(deps)}개 모집단위는"



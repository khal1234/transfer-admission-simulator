export function getDepartmentCategory(department: string): DepartmentCategory {
  const override = OVERRIDES[department];
  if (override !== undefined) {
    return override;
  }

  for (const [category, pattern] of RULES) {
    if (pattern.test(department)) {
      return category;
    }
  }

  return "기타";
}

export function getCategoryTrack(category: DepartmentCategory): CategoryTrack {
  return CATEGORY_TRACKS.find((group) => group.categories.includes(category))?.track ?? "그 외";
}

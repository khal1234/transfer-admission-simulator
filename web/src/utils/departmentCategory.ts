/**
 * 학과명만으로 계열(단과대 성격)을 가른다.
 *
 * 데이터에 단과대 정보가 없어서 이름의 낱말로 나눈다. 같은 학과가 학교마다
 * 다른 단과대에 붙어 있어도(예: 경제학과가 사회대이기도 상경대이기도) 화면에선
 * 학생이 떠올리는 계열 하나로 묶는다. 순서가 판정을 정한다 — 앞 규칙이 먼저 잡는다.
 *   · 사범을 맨 앞에: '수학교육과'가 자연으로 가지 않게
 *   · 공학을 그다음에: '화학공학과'·'식품공학과'·'섬유공학전공'은 공학
 *   · 농생명을 의약보다 앞에: '식물의학과'가 의약으로 가지 않게
 *   · 자연을 맨 뒤에: '과학'·'환경'이 넓어서 '인문사회과학'·'자원환경경제'를 먼저 빼앗는다
 * 못 보는 것: 이름에 계열 단서가 없는 융합학과는 '기타'로 떨어진다.
 */

export type DepartmentCategory =
  | "공학"
  | "자연"
  | "농생명"
  | "의약보건"
  | "인문"
  | "사회"
  | "상경"
  | "사범"
  | "예체능"
  | "기타";

export type CategoryTrack = "이과" | "문과" | "그 외";

export const CATEGORY_TRACKS: { track: CategoryTrack; categories: DepartmentCategory[] }[] = [
  { track: "이과", categories: ["공학", "자연", "농생명", "의약보건"] },
  { track: "문과", categories: ["인문", "사회", "상경"] },
  { track: "그 외", categories: ["사범", "예체능", "기타"] },
];

// 이름만으로는 틀리게 잡히는 학과. 낱말 규칙을 비틀어 맞추는 것보다 여기 적는 편이 덜 번진다.
const OVERRIDES: Record<string, DepartmentCategory> = {
  "경제·정보통계학부(정보통계학전공)": "자연",
  "전자상거래전공": "상경",
  "고고미술사학과": "인문",
};

